/**
 * db.ts — Drizzle + PostgreSQL（node-postgres）（lib: 共通インスタンス）。
 *
 * DB は DATABASE_URL で接続する PostgreSQL。未設定なら DB 機能は
 * 利用不可（getDb() が null を返す）で、DB 不要の計算 API だけが動く。
 * import 時点では接続しない（初回利用時にプールを遅延作成する）。
 */
import { drizzle, NodePgDatabase } from "drizzle-orm/node-postgres";
import { sql } from "drizzle-orm";
import { Pool } from "pg";
import * as schema from "../repositories/schema";

export type Db = NodePgDatabase<typeof schema>;

let cached: Db | null = null;
let attempted = false;

/** DB が利用可能か（DATABASE_URL が設定されているか）。 */
export function isDatabaseConfigured(): boolean {
  return Boolean(process.env.DATABASE_URL);
}

/** DBインスタンスを返す。DATABASE_URL 未設定なら null（接続プールはここで初めて作る）。 */
export function getDb(): Db | null {
  if (cached) return cached;
  const url = process.env.DATABASE_URL;
  if (!url) return null;
  attempted = true;
  const pool = new Pool({ connectionString: url });
  cached = drizzle(pool, { schema });
  return cached;
}

/** DB接続を試みたことがあるか。 */
export function dbWasAttempted(): boolean {
  return attempted;
}

