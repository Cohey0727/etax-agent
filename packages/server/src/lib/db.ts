/** 指定した DB にスキーマ DDL を適用する（冪等）。 */
export async function applySchema(db: Db): Promise<void> {
  for (const statement of schemaDdl) {
    await db.execute(sql.raw(statement));
  }
}

let tablesEnsured = false;
let ensuring: Promise<void> | null = null;

/**
 * 本番 DB のテーブルが無ければ作る（冪等）。起動時に呼ぶ。
 * 起動処理と初回リクエストの待機から同時に呼ばれても、実行中の初期化を
 * 共有して DDL を1回だけ流す（並行した CREATE … IF NOT EXISTS は
 * 一意制約違反で失敗しうる）。失敗したら次の呼び出しでやり直す。
 */
export function ensureTables(): Promise<void> {
  if (tablesEnsured) return Promise.resolve();
  ensuring ??= (async () => {
    try {
      // DB 未設定なら用意すべきものは無い（完了扱いにして待機側を進める）。
      const db = getDb();
      if (db) await applySchema(db);
      tablesEnsured = true;
    } finally {
      ensuring = null;
    }
  })();
  return ensuring;
}

let readyPromise: Promise<void> | null = null;

/**
 * テーブル初期化の完了を待つ共有 Promise。初期化はバックグラウンドで
 * 進むため、DB を使う処理はこれを await してから走ると安全になる。
 * DB が落ちている場合は上限まで待ってから諦める（各リクエスト側で
 * さらに短いタイムアウトを併用すること）。
 */
export function tablesReady(): Promise<void> {
  if (!readyPromise) {
    readyPromise = (async () => {
      const maxAttempts = 60;
      for (let attempt = 0; attempt < maxAttempts && !tablesEnsured; attempt++) {
        try {
          await ensureTables();
        } catch {
          // 初期化のリトライは起動側ループも行う。ここでは待機に徹する。
        }
        if (!tablesEnsured) {
          await new Promise((resolve) => setTimeout(resolve, 500));
        }
      }
    })();
  }
  return readyPromise;
}
